/*
 * Web build for GitHub Pages under /woodstock/ (mobile-lead). Offline: no Expo login, no network.
 *   1. expo export --platform web  -> dist/
 *   2. 404.html = index.html, so deep links (/woodstock/plan) load the SPA on GitHub Pages
 *   3. sw.js: precaches every exported file; network-first for pages, cache-first for hashed assets
 *   4. .nojekyll, so GitHub Pages serves the _expo/ folder
 *   5. build.json: version, commit, time
 */
import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dist = path.join(root, "dist");
const BASE = "/woodstock/";
const env = { ...process.env, EXPO_OFFLINE: "1", EXPO_NO_TELEMETRY: "1", CI: "1", NODE_ENV: "production" };

fs.rmSync(dist, { recursive: true, force: true });
execSync("npx expo export --platform web --output-dir dist --clear", { cwd: root, env, stdio: "inherit" });

const index = path.join(dist, "index.html");
if (!fs.existsSync(index)) throw new Error("export produced no index.html");
fs.copyFileSync(index, path.join(dist, "404.html"));
fs.writeFileSync(path.join(dist, ".nojekyll"), "");

/* A copy of index.html at every static route, so a deep link or a reload answers 200, not 404. */
const routes = [];
(function walkRoutes(d, parts) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) { walkRoutes(p, /^\(.*\)$/.test(f) ? parts : [...parts, f]); continue; }
    const m = f.match(/^([^_+\[][^.]*)\.tsx?$/); if (!m) continue;
    const segs = m[1] === "index" ? parts : [...parts, m[1]];
    if (segs.some((x) => x.startsWith("["))) continue;
    if (segs.length) routes.push(segs.join("/"));
  }
})(path.join(root, "app"), []);
for (const r of new Set(routes)) {
  if (fs.existsSync(path.join(dist, r + ".html"))) continue;
  fs.mkdirSync(path.join(dist, r), { recursive: true });
  fs.copyFileSync(index, path.join(dist, r, "index.html"));
}
console.log("static route pages: " + [...new Set(routes)].join(", "));

const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else files.push(path.relative(dist, p).split(path.sep).join("/"));
  }
})(dist);
const precache = files.filter((f) => !/^(sw\.js|404\.html|\.nojekyll|build\.json|metadata\.json)$/.test(f) && !(/\/index\.html$/.test(f))).map((f) => BASE + (f === "index.html" ? "" : f));
let commit = "nogit";
try { commit = execSync("git rev-parse --short HEAD", { cwd: root }).toString().trim(); } catch {}
const version = new Date().toISOString().replace(/[-:T]/g, "").slice(0, 12) + "-" + commit;

const sw = `/* Woodstock service worker ${version}. Generated by scripts/build-web.mjs. */
const CACHE = "woodstock-${version}";
const BASE = "${BASE}";
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("woodstock-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("fetch", (e) => {
  const req = e.request; const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== location.origin || !url.pathname.startsWith(BASE)) return;
  if (req.mode === "navigate") {
    e.respondWith(fetch(req).then((r) => { const copy = r.clone(); if (r.ok) caches.open(CACHE).then((c) => c.put(BASE, copy)); return r; }).catch(() => caches.match(BASE)));
    return;
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((r) => { if (r.ok) { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); } return r; })));
});
`;
fs.writeFileSync(path.join(dist, "sw.js"), sw);
fs.writeFileSync(path.join(dist, "build.json"), JSON.stringify({ version, commit, builtAt: new Date().toISOString(), base: BASE, files: files.length }, null, 2));
console.log(`web build ready: dist/ (${files.length} files, ${version})`);
