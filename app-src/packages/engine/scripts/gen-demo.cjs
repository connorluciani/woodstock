#!/usr/bin/env node
/* Regenerates src/demo/alandra.ts from a prototype release's WS.state literal (dev only).
   Usage: node packages/engine/scripts/gen-demo.cjs /home/claude/app/releases/woodstock_v7_3_2.html */
"use strict";
const fs = require("fs"), path = require("path");
const html = fs.readFileSync(process.argv[2] || "/home/claude/app/releases/woodstock_v7_3_2.html", "utf8");
const i = html.indexOf("WS.state = {"); if (i < 0) throw new Error("WS.state not found");
let j = html.indexOf("{", i), depth = 0, inStr = false, esc = false, k = j;
for (; k < html.length; k++) {
  const ch = html[k];
  if (inStr) { if (esc) esc = false; else if (ch === "\\") esc = true; else if (ch === '"') inStr = false; continue; }
  if (ch === '"') inStr = true; else if (ch === "{") depth++; else if (ch === "}") { depth--; if (!depth) break; }
}
const state = JSON.parse(html.slice(j, k + 1));
const out = `/* Alandra Gray, the demo persona: the prototype's WS.state literal from releases/${path.basename(process.argv[2] || "woodstock_v7_3_2.html")}, unchanged
   (generated by scripts/gen-demo.cjs; do not edit by hand). Made-up person and numbers. */
import type { DemoState } from "../types.ts";

export const ALANDRA: DemoState = ${JSON.stringify(state, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, "..", "src", "demo", "alandra.ts"), out);
console.log("wrote src/demo/alandra.ts");
